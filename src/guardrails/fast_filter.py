"""
Быстрый regex-фильтр для guardrails.

Ловит ~90% запрещённых запросов. Оставшиеся 10% (замаскированные)
добирает NeMo Guardrails — если он подключён.

Две точки применения:
  - check_input(text)  → True = запрос заблокировать
  - check_output(text) → True = ответ заблокировать
"""
from __future__ import annotations

import re
import unicodedata


# ============================================================================
#  НОРМАЛИЗАЦИЯ
# ============================================================================

def _normalize(text: str) -> str:
    """
    Приводит текст к виду, удобному для regex-поиска:
      - Unicode NFKC (ё → е, ﬁ → fi, латинские похожие → кириллица и т.д.)
      - нижний регистр
      - заменяет разделители (., -, _, *, |, /, пробелы) между буквами на пусто
        чтобы поймать "о б н а л", "о.б.н.а.л", "о-б-н-а-л"
    """
    text = unicodedata.normalize("NFKC", text).lower()
    # Схлопываем буквы, разделённые мусором: "о б н а л" → "обнал"
    # Работает для кириллицы и латиницы.
    text = re.sub(r"(?<=[а-яёa-z])[\s\.\-_\*\|\/,]+(?=[а-яёa-z])", "", text)
    return text


# ============================================================================
#  ВХОДНОЙ ЧЁРНЫЙ СПИСОК
# ============================================================================

# Каждый элемент — регулярка. Используем группы `(?:...)`, чтобы не ловить
# лишнее. Основной приём — префиксы корней: "обнал" поймает "обналичить",
# "обналичка", "обнала", "обналил" и т.д.
_INPUT_PATTERNS: list[str] = [
    # --- Обнал и теневые схемы ---------------------------------------------
    r"обнал",                     # обнал, обналичить, обналичка, обналил
    r"обналь",
    r"кэш\s*аут",
    r"каш\s*аут",
    r"cash\s*out",

    # --- Уход от налогов ---------------------------------------------------
    r"уйти\s*от\s*налог",
    r"уход\s*от\s*налог",
    r"уклонит\w*\s*от\s*налог",
    r"не\s*платить\s*налог",
    r"не\s*хочу\s*платить\s*налог",
    r"скрыть\s*доход",
    r"сокрыти\w*\s*доход",
    r"занизить\s*налог",
    r"занизить\s*доход",
    r"занизить\s*прибыл",
    r"оптимизац\w*\s*налог",      # двусмысленно, но чаще про схемы
    r"налогов\w*\s*схем",
    r"налогов\w*\s*оптимизац",

    # --- Фирмы-однодневки и подставные -------------------------------------
    r"однодневк",
    r"фирм\w*[\s\-]*однодневк",
    r"подставн\w*\s*фирм",
    r"подставн\w*\s*компан",
    r"подставн\w*\s*лиц",
    r"номинальн\w*\s*директор",
    r"номинальн\w*\s*учредител",
    r"фиктивн\w*\s*директор",
    r"фиктивн\w*\s*сделк",
    r"фиктивн\w*\s*договор",
    r"фиктивн\w*\s*счёт",
    r"фиктивн\w*\s*счет",
    r"фиктивн\w*\s*счёт",
    r"липов\w*\s*документ",
    r"липов\w*\s*фирм",
    r"левая\s*фирм",
    r"левые\s*документ",

    # --- Подделка документов и подписей ------------------------------------
    r"подделать\s*подпис",
    r"подделать\s*документ",
    r"подделать\s*счёт",
    r"подделать\s*счет",
    r"подделать\s*печат",
    r"подделать\s*штамп",
    r"фальшив\w*\s*подпис",
    r"фальшив\w*\s*документ",
    r"поддельн\w*\s*подпис",
    r"поддельн\w*\s*печат",
    r"сфабриковать\s*документ",
    r"сфабриковать\s*сделк",

    # --- Отмывание денег ---------------------------------------------------
    r"отмыть\s*деньг",
    r"отмыв\w*\s*денег",
    r"отмыван\w*\s*денег",
    r"money\s*launder",
    r"прачечн\w*\s*для\s*денег",
    r"легализац\w*\s*доход",
    r"легализовать\s*деньг",

    # --- Конвертация / обналичивание через фирмы ---------------------------
    r"конвертац\w*\s*денег",
    r"конвертн\w*\s*центр",
    r"обнальн\w*\s*площадк",
    r"обнальн\w*\s*контор",

    # --- Взломы / кражи в корпоративном контексте --------------------------
    r"взломать\s*1с",
    r"взломать\s*бухгалтер",
    r"взломать\s*налогов",
    r"взломать\s*банк",
    r"украсть\s*деньг",
    r"украсть\s*из\s*касс",
    r"вывести\s*деньг\w*\s*из\s*фирм",
    r"вывести\s*актив",

    # --- Мат (грубые корни, чтобы не ловить ложные срабатывания) ----------
    r"ебан", r"ебал", r"ебуч",
    r"пизд",
    r"бляд", r"блят",
    r"мудак", r"мудил",
    r"херн", r"хуйн", r"хуй",
    r"сука\b", r"суки\b",
    r"долбоёб", r"долбоеб",

    # --- Английские эквиваленты -------------------------------------------
    r"tax\s*evasion",
    r"tax\s*avoidance",
    r"shell\s*compan",
    r"fake\s*invoice",
    r"fraudulent\s*document",
    r"forge\s*signatur",
]

# Один большой скомпилированный регексп — быстрее, чем N отдельных поисков.
_INPUT_RE = re.compile(
    "|".join(f"(?:{p})" for p in _INPUT_PATTERNS),
    re.IGNORECASE,
)


# ============================================================================
#  ВЫХОДНОЙ ЧЁРНЫЙ СПИСОК (защита от утечек)
# ============================================================================

# Ловим форматы ПДн и платёжных данных в ответе модели.
# Требовательны к формату, чтобы не блокировать обычные числа (суммы, счета).
_OUTPUT_PATTERNS: list[str] = [
    # --- ИНН ---------------------------------------------------------------
    # 10 цифр (юрлицо) или 12 цифр (физлицо/ИП)
    r"\bИНН[:\s]*\d{10,12}\b",
    r"\bINN[:\s]*\d{10,12}\b",

    # --- СНИЛС -------------------------------------------------------------
    # Формат XXX-XXX-XXX YY (с дефисами) или 11 цифр подряд
    r"\bСНИЛС[:\s]*\d{3}[\-\s]?\d{3}[\-\s]?\d{3}[\s]?\d{2}\b",
    r"\bSNILS[:\s]*\d{3}[\-\s]?\d{3}[\-\s]?\d{3}[\s]?\d{2}\b",

    # --- Паспорт РФ --------------------------------------------------------
    # "паспорт 1234 567890" или "серия 1234 номер 567890"
    r"\bпаспорт\w*[:\s]*\d{4}[\s\-]?\d{6}\b",
    r"\bсерия[:\s]*\d{4}[,\s]*номер[:\s]*\d{6}\b",
    r"\bсерия[:\s]*\d{2}\s*\d{2}\b.*\bномер[:\s]*\d{6}\b",

    # --- Банковская карта --------------------------------------------------
    # 16 цифр, возможно с пробелами/дефисами: 1234 5678 9012 3456
    r"\b(?:\d[ \-]?){15}\d\b",

    # --- Расчётный счёт ----------------------------------------------------
    # 20 цифр подряд
    r"\b\d{20}\b",
    r"\bрасч[её]тный\s*сч[её]т[:\s]*\d{20}\b",
    r"\bр/с[:\s]*\d{20}\b",

    # --- БИК + корсчёт в явном виде ---------------------------------------
    r"\bБИК[:\s]*\d{9}\b.*\bкорр?\.?\s*сч[её]т[:\s]*\d{20}\b",

    # --- CVC/CVV -----------------------------------------------------------
    # Только если явно упомянуты — иначе поймает всё подряд
    r"\bCVV[:\s]*\d{3}\b",
    r"\bCVC[:\s]*\d{3}\b",

    # --- Пароли в явном виде ----------------------------------------------
    # "пароль: xxx", "password=xxx"
    r"\bпароль[:\s=]+\S{4,}\b",
    r"\bpassword[:\s=]+\S{4,}\b",
]

_OUTPUT_RE = re.compile(
    "|".join(f"(?:{p})" for p in _OUTPUT_PATTERNS),
    re.IGNORECASE,
)


# ============================================================================
#  ПУБЛИЧНЫЙ API
# ============================================================================

def check_input(text: str) -> bool:
    """
    Проверяет пользовательский запрос.
    Возвращает True, если запрос нужно ЗАБЛОКИРОВАТЬ.
    """
    if not text:
        return False
    normalized = _normalize(text)
    return bool(_INPUT_RE.search(normalized))


def check_output(text: str) -> bool:
    """
    Проверяет ответ модели.
    Возвращает True, если ответ содержит утечку и его нужно ЗАБЛОКИРОВАТЬ.
    """
    if not text:
        return False
    # Выход НЕ нормализуем так же агрессивно, как вход:
    # цифры должны остаться с разделителями, иначе "1234 5678 9012 3456"
    # склеится в "1234567890123456" и потеряет форму карты.
    return bool(_OUTPUT_RE.search(text))


